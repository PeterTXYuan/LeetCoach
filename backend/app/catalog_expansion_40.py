def guide(key, name, pattern, summary, quote, signals, steps, *, primary=True, order=1):
    return {
        "id": key, "name": name, "pattern": pattern, "summary": summary,
        "isPrimary": primary, "displayOrder": order,
        "thinkingSteps": steps,
        "recognitionSignals": {"quote": quote, "bullets": signals},
    }


def entry(description, summary, approaches, *, easier=(), similar=(), harder=(),
          time=None, space=None):
    return {
        "description": description, "summary": summary,
        "approaches": approaches,
        "related": {"easier": easier, "similar": similar, "harder": harder},
        "timeComplexityInstruction": time,
        "spaceComplexityInstruction": space,
    }


